import { describe, it, expect } from "vitest";
import { bahtWords, esc } from "@/lib/contract-builder";

// bahtWords อยู่บนสัญญาซื้อขายจริง — ถ้าตัวอักษรเงินผิด = เอกสารกฎหมายผิด
// เทสต์ครอบกฎไทยที่พลาดบ่อย: เอ็ด, ยี่สิบ, ล้าน, ศูนย์, ปัดเศษ
describe("bahtWords — แปลงจำนวนเงินเป็นตัวอักษรไทย", () => {
  it("ศูนย์", () => {
    expect(bahtWords(0)).toBe("(ศูนย์บาทถ้วน)");
  });

  it("หลักหน่วยเดี่ยว (ไม่ใช่ เอ็ด)", () => {
    expect(bahtWords(1)).toBe("(หนึ่งบาทถ้วน)");
  });

  it("11 ต้องเป็น 'สิบเอ็ด' ไม่ใช่ 'สิบหนึ่ง'", () => {
    expect(bahtWords(11)).toBe("(สิบเอ็ดบาทถ้วน)");
  });

  it("20 ต้องเป็น 'ยี่สิบ'", () => {
    expect(bahtWords(20)).toBe("(ยี่สิบบาทถ้วน)");
  });

  it("21 = ยี่สิบเอ็ด", () => {
    expect(bahtWords(21)).toBe("(ยี่สิบเอ็ดบาทถ้วน)");
  });

  it("100 = หนึ่งร้อย", () => {
    expect(bahtWords(100)).toBe("(หนึ่งร้อยบาทถ้วน)");
  });

  it("ราคารับซื้อจริง 18,000", () => {
    expect(bahtWords(18000)).toBe("(หนึ่งหมื่นแปดพันบาทถ้วน)");
  });

  it("หลักล้านพอดี", () => {
    expect(bahtWords(1000000)).toBe("(หนึ่งล้านบาทถ้วน)");
  });

  it("ตัวเลขใหญ่ครบทุกหลัก 1,234,567", () => {
    expect(bahtWords(1234567)).toBe("(หนึ่งล้านสองแสนสามหมื่นสี่พันห้าร้อยหกสิบเจ็ดบาทถ้วน)");
  });

  it("ปัดเศษสตางค์ขึ้นเป็นบาท (17999.5 → 18000)", () => {
    expect(bahtWords(17999.5)).toBe("(หนึ่งหมื่นแปดพันบาทถ้วน)");
  });
});

describe("esc — กัน HTML injection ในเอกสาร", () => {
  it("escape อักขระพิเศษ < > & \"", () => {
    expect(esc('ชื่อ <b>&"')).toBe("ชื่อ &lt;b&gt;&amp;&quot;");
  });

  it("ข้อความปกติไม่เปลี่ยน", () => {
    expect(esc("สมชาย ใจดี")).toBe("สมชาย ใจดี");
  });

  it("ค่าว่าง/undefined → string ว่าง", () => {
    expect(esc(undefined as unknown as string)).toBe("");
  });
});
